"""SYNTHETIC customers for evaluating sanctions screening. Every name here is generated; none is a real customer.

Three groups, each with ground truth:
- clean (5,000): small-business owners and businesses made up with Faker. A clean name whose normalized form
  exactly equals a list name is dropped and counted (a "collision"), as is a repeated clean name.
  The collisions are not thrown away: each distinct one is kept as an "exact_name_homonym", a made-up customer
  who happens to share a listed name. They are written to a separate file (homonyms.csv), are not in any split,
  and are scored separately, because a name-only screener is right to alert on them and leaving them out of the
  clean group makes its alert volume a lower bound for a real name population.
- true_match (150): a real list entry's name (OFAC SDN or an OpenSanctions entry on a sanctions program) with
  realistic noise: transliteration variants, typos, initials, token reordering, legal-suffix changes,
  honorifics. Ground truth is the list entry it came from.
- hard_negative (150): a different identity deliberately close to a list name: a list person's name with one
  part (a given name or the surname) replaced by a different-sounding name with the same first letter, or a
  list organization's name with about half of its words replaced. Exact collisions with any list name are
  dropped and counted.

Customers are split into train / validation / test, stratified by group, with a fixed seed.
"""

