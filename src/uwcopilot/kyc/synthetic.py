def title_case(tokens: list[str]) -> str:
    """Join tokens as a display name: "mohammed ali" -> "Mohammed Ali"."""
    return " ".join(token.capitalize() for token in tokens)


def natural_order(name: str, entity_type: str) -> str:
    """OFAC writes people as "SURNAME, Given Names"; return "Given Names SURNAME" for persons."""
    if entity_type == "person" and name.count(",") == 1:
        surname, given = (part.strip() for part in name.split(","))
        if surname and given:
            return f"{given} {surname}"
    return name


# ---------------------------------------------------------------------------------------------------------------
# Noise operations for true matches. Each takes and returns a list of lowercase tokens (or a display string).
# ---------------------------------------------------------------------------------------------------------------


def apply_transliteration(tokens: list[str], rng: random.Random) -> list[str] | None:
    """Swap one spelling pattern in one token (e.g. "mohammed" -> "muhammad"). None if no rule applies."""
    text = " ".join(tokens)
    options = [(source, target) for source, target in TRANSLITERATION_RULES if source in text]
    if not options:
        return None
    source, target = rng.choice(options)
    positions = [i for i in range(len(text)) if text.startswith(source, i)]
    position = rng.choice(positions)
    changed = text[:position] + target + text[position + len(source) :]
    return changed.split()


def apply_typo(tokens: list[str], rng: random.Random) -> list[str] | None:
    """One keyboard-style typo (substitute, delete, insert or swap letters) in one token of 4+ letters."""
    eligible = [i for i, token in enumerate(tokens) if len(token) >= 4 and token.isalpha()]
    if not eligible:
        return None
    index = rng.choice(eligible)
    token = tokens[index]
    position = rng.randrange(1, len(token) - 1)  # keep the first letter, as most real typos do
    kind = rng.choice(["substitute", "delete", "insert", "transpose"])
    if kind == "substitute":
        letter = rng.choice([c for c in LETTERS if c != token[position]])
        token = token[:position] + letter + token[position + 1 :]
    elif kind == "delete":
        token = token[:position] + token[position + 1 :]
    elif kind == "insert":
        token = token[:position] + rng.choice(LETTERS) + token[position:]
    else:
        token = token[:position] + token[position + 1] + token[position] + token[position + 2 :]
    changed = list(tokens)
    changed[index] = token
    return changed


def apply_initials(tokens: list[str], rng: random.Random) -> list[str] | None:
    """Shorten one given or middle name to its initial ("Mohammed Ali Hassan" -> "M Ali Hassan")."""
    eligible = [i for i, token in enumerate(tokens[:-1]) if len(token) >= 2]
    if len(tokens) < 2 or not eligible:
        return None
    index = rng.choice(eligible)
    changed = list(tokens)
    changed[index] = tokens[index][0]
    return changed


def apply_reorder(tokens: list[str], rng: random.Random) -> list[str] | None:
    """Move the last token to the front (surname first) or swap two tokens; None for one-token names."""
    if len(tokens) < 2:
        return None
    if rng.random() < 0.5:
        changed = [tokens[-1], *tokens[:-1]]
    else:
        changed = list(tokens)
        i, j = rng.sample(range(len(tokens)), 2)
        changed[i], changed[j] = changed[j], changed[i]
    return changed if changed != tokens else None


NOISE_FUNCTIONS: dict[str, Callable[[list[str], random.Random], list[str] | None]] = {
    "transliteration": apply_transliteration,
    "typo": apply_typo,
    "initials": apply_initials,
    "token_reorder": apply_reorder,
}


def noisy_variant(tokens: list[str], entity_type: str, rng: random.Random) -> tuple[str, list[str]]:
    """Apply one to three noise operations to a list name; return (display name, operations applied).

    Token-level operations come first; then persons may get an honorific and organizations a different legal
    suffix, which normalization will strip again (as it would for a real customer).
    """
    operations = PERSON_NOISE_OPS if entity_type == "person" else ORGANIZATION_NOISE_OPS
    wanted = rng.sample(operations, k=rng.choice([1, 1, 2, 2, 3]))
    applied: list[str] = []
    current = list(tokens)
    for operation in wanted:
        function = NOISE_FUNCTIONS.get(operation)
        if function is None:
            continue
        changed = function(current, rng)
        if changed is not None and changed != current:
            current = changed
            applied.append(operation)
    display = title_case(current)
    if "honorific" in wanted:
        if rng.random() < 0.75:
            display = f"{rng.choice(HONORIFIC_PREFIXES)} {display}"
        else:
            display = f"{display} {rng.choice(HONORIFIC_SUFFIXES)}"
        applied.append("honorific")
    if entity_type == "organization" and "suffix_change" in wanted:
        display = f"{display} {rng.choice(LEGAL_SUFFIXES)}"
        applied.append("suffix_change")
    if not applied:
        applied.append("none")
    return display, applied


# ---------------------------------------------------------------------------------------------------------------
# Hard negatives: a different identity that is deliberately close to a list name.
# ---------------------------------------------------------------------------------------------------------------


def sounds_different(left: str, right: str, max_jaro_winkler: float = 0.8) -> bool:
    """True when two tokens share no Double Metaphone code and are not similar in spelling."""
    if left == right:
        return False
    if set(phonetic_codes(left)) & set(phonetic_codes(right)):
        return False
    return JaroWinkler.normalized_similarity(left, right) < max_jaro_winkler


def pick_different(word_source: Callable[[], str], original: str, tries: int = 50) -> str | None:
    """Draw words until one sounds different from `original` (one lowercase token), or give up."""
    for _ in range(tries):
        candidate_tokens = normalize_name(word_source(), "person").tokens
        if len(candidate_tokens) == 1 and sounds_different(candidate_tokens[0], original):
            return candidate_tokens[0]
    return None


def same_initial_word(word_source: Callable[[], str], initial: str, tries: int = 30) -> Callable[[], str]:
    """Wrap a Faker word source so it prefers words starting with `initial` (falls back to any word)."""

    def draw() -> str:
        """Return the first drawn word with the wanted initial, or the last word drawn."""
        word = word_source()
        for _ in range(tries):
            if word[:1].lower() == initial:
                return word
            word = word_source()
        return word

    return draw


def hard_negative_person(tokens: list[str], fake: Faker, rng: random.Random) -> tuple[list[str], str] | None:
    """Replace exactly one name part with a different-sounding name that starts with the same letter.

    "Mohammed Ali Hassan" can become "Mohammed Ali Harrison" (different surname) or "Mohammed Aaron Hassan"
    (different given name): close in spelling, but a different person.
    """
    if len(tokens) < 2:
        return None
    position = rng.randrange(len(tokens))
    original = tokens[position]
    if position == len(tokens) - 1:
        source, strategy = same_initial_word(fake.last_name, original[0]), "different_surname"
    else:
        source, strategy = same_initial_word(fake.first_name, original[0]), "different_given_name"
    replacement = pick_different(source, original)
    if replacement is None or replacement in tokens:
        return None
    changed = list(tokens)
    changed[position] = replacement
    return changed, strategy


def hard_negative_organization(tokens: list[str], rng: random.Random) -> tuple[list[str], str] | None:
    """Replace about half of an organization's words with unrelated business words, keeping its longest word.

    Keeping the most distinctive word ("Elessa Group" -> "Elessa Bakery") makes the name deliberately close to
    the listed one while describing a different business.
    """
    if len(tokens) < 2:
        return None
    longest = max(range(len(tokens)), key=lambda i: len(tokens[i]))
    replaceable = [i for i in range(len(tokens)) if i != longest]
    count = max(1, len(tokens) // 2)
    positions = rng.sample(replaceable, min(count, len(replaceable)))
    changed = list(tokens)
    vocabulary = [word.lower() for word in BUSINESS_WORDS + DESCRIPTIVE_WORDS if " " not in word]
    for position in positions:
        options = [word for word in vocabulary if sounds_different(word, tokens[position]) and word not in tokens]
        if not options:
            return None
        changed[position] = rng.choice(options)
    return changed, "different_words"


