def stratified_split(
    labels: list[str], seed: int, fractions: tuple[float, float, float] = SPLIT_FRACTIONS
) -> list[str]:
    """Assign train/validation/test within each label so every split has the same label mix."""
    rng = np.random.default_rng(seed)
    splits = [""] * len(labels)
    for label in sorted(set(labels)):
        indices = np.array([i for i, value in enumerate(labels) if value == label])
        rng.shuffle(indices)
        train_end = math.floor(len(indices) * fractions[0])
        validation_end = train_end + math.floor(len(indices) * fractions[1])
        for position, index in enumerate(indices):
            if position < train_end:
                splits[index] = "train"
            elif position < validation_end:
                splits[index] = "validation"
            else:
                splits[index] = "test"
    return splits


def customer_record(name: str, entity_type: str, country: str | None, label: str, **extra: str) -> dict:
    """One customer row with every ground-truth column present."""
    record = {
        "name": name,
        "entity_type": entity_type,
        "country": country or "",
        "label": label,
        "matched_list_entry_id": "",
        "derived_from_list_entry_id": "",
        "derived_from_name": "",
        "generation": "",
        "synthetic": SYNTHETIC_LABEL,
    }
    record.update(extra)
    return record


def make_clean_customers(
    config: GenerationConfig,
    list_keys: set[str],
    rng: random.Random,
    fake: Faker,
    homonyms: list[dict] | None = None,
) -> tuple[list[dict], dict]:
    """Generate clean customers until config.clean_count remain after dropping collisions and duplicates.

    homonyms, if given, receives one record per distinct collision (label exact_name_homonym, no country). Keeping
    them draws no extra random numbers, so the clean customers are the same with or without the list.
    """
    records: list[dict] = []
    seen_keys: set[str] = set()
    homonym_keys: set[str] = set()
    counts = {"generated": 0, "dropped_list_collisions": 0, "dropped_duplicates": 0, "collision_examples": []}
    max_attempts = config.clean_count * config.max_attempts_factor
    while len(records) < config.clean_count and counts["generated"] < max_attempts:
        counts["generated"] += 1
        if rng.random() < 0.5:
            entity_type, name, generator = "person", clean_person_name(fake), "faker_person"
        else:
            entity_type = "organization"
            name, generator = clean_business_name(fake, rng)
        key = collision_key(name, entity_type)
        if not key or key in list_keys:
            counts["dropped_list_collisions"] += 1
            if len(counts["collision_examples"]) < 10:
                counts["collision_examples"].append(name)
            if homonyms is not None and key and key not in homonym_keys:
                homonym_keys.add(key)
                homonyms.append(customer_record(name, entity_type, None, HOMONYM_LABEL, generation=generator))
            continue
        if key in seen_keys:
            counts["dropped_duplicates"] += 1
            continue
        seen_keys.add(key)
        records.append(customer_record(name, entity_type, clean_country(rng), "clean", generation=generator))
    counts["kept"] = len(records)
    counts["distinct_exact_name_homonyms"] = len(homonym_keys)
    return records, counts


def derived_country(
    entry_countries: tuple[str, ...], same_country_probability: float, rng: random.Random
) -> str | None:
    """Use the list entry's country with the given probability; otherwise a clean-style country or none."""
    if entry_countries and rng.random() < same_country_probability:
        return entry_countries[0].upper()
    return None if rng.random() < 0.5 else clean_country(rng)


def make_true_matches(
    entries: pd.DataFrame, pools: dict, config: GenerationConfig, rng: random.Random
) -> tuple[list[dict], set[int], dict]:
    """150 noisy versions of real list names: half OFAC, half OpenSanctions; half persons, half organizations."""
    per_cell = config.true_match_count // 4
    targets = {key: per_cell for key in pools}
    for key in list(targets)[: config.true_match_count - 4 * per_cell]:
        targets[key] += 1
    records: list[dict] = []
    used_rows: set[int] = set()
    skipped = 0
    for (source, entity_type), target in targets.items():
        pool = list(pools[(source, entity_type)])
        rng.shuffle(pool)
        made = 0
        for row in pool:
            if made >= target:
                break
            original = pick_source_name(entries, int(row), rng, config.alias_probability)
            tokens = latin_tokens(original, entity_type)
            if not usable_source(tokens, entity_type):
                skipped += 1
                continue
            name, operations = noisy_variant(tokens, entity_type, rng)
            country = derived_country(entries["countries"].iat[int(row)], 0.5, rng)
            entry_id = entries["list_entry_id"].iat[int(row)]
            records.append(
                customer_record(
                    name,
                    entity_type,
                    country,
                    "true_match",
                    matched_list_entry_id=entry_id,
                    derived_from_list_entry_id=entry_id,
                    derived_from_name=original,
                    generation="+".join(operations),
                )
            )
            used_rows.add(int(row))
            made += 1
    report = {"kept": len(records), "source_names_skipped_not_latin_or_unusable": skipped}
    return records, used_rows, report


def make_hard_negatives(
    entries: pd.DataFrame,
    pools: dict,
    config: GenerationConfig,
    list_keys: set[str],
    excluded_rows: set[int],
    rng: random.Random,
    fake: Faker,
) -> tuple[list[dict], dict]:
    """150 names close to a list name but belonging to someone else; collisions with any list name are dropped."""
    per_type = {"person": config.hard_negative_count // 2}
    per_type["organization"] = config.hard_negative_count - per_type["person"]
    records: list[dict] = []
    counts = {"dropped_list_collisions": 0, "skipped_unusable_source": 0, "strategies": {}}
    for entity_type, target in per_type.items():
        pool = [int(row) for key, rows in pools.items() if key[1] == entity_type for row in rows]
        rng.shuffle(pool)
        made = 0
        for row in pool:
            if made >= target:
                break
            if row in excluded_rows:
                continue
            original = pick_source_name(entries, row, rng, config.alias_probability)
            tokens = latin_tokens(original, entity_type)
            if not usable_source(tokens, entity_type):
                counts["skipped_unusable_source"] += 1
                continue
            if entity_type == "person":
                built = hard_negative_person(tokens, fake, rng)
            else:
                built = hard_negative_organization(tokens, rng)
            if built is None:
                counts["skipped_unusable_source"] += 1
                continue
            new_tokens, strategy = built
            name = title_case(new_tokens)
            if entity_type == "organization" and rng.random() < 0.5:
                name = f"{name} {rng.choice(LEGAL_SUFFIXES)}"
            if collision_key(name, entity_type) in list_keys:
                counts["dropped_list_collisions"] += 1
                continue
            country = derived_country(entries["countries"].iat[row], 0.4, rng)
            records.append(
                customer_record(
                    name,
                    entity_type,
                    country,
                    "hard_negative",
                    derived_from_list_entry_id=entries["list_entry_id"].iat[row],
                    derived_from_name=original,
                    generation=strategy,
                )
            )
            counts["strategies"][strategy] = counts["strategies"].get(strategy, 0) + 1
            made += 1
    counts["kept"] = len(records)
    return records, counts


def generate_customers(
    entries: pd.DataFrame,
    list_keys: set[str],
    config: GenerationConfig | None = None,
    homonyms_out: list[dict] | None = None,
) -> tuple[pd.DataFrame, dict]:
    """Make all three groups, assign ids and splits. Returns (customers table, generation report).

    homonyms_out, if given, receives the exact-name homonym records (ids SYN-KYC-H-00001, ...; no split).
    """
    config = config or GenerationConfig()
    rng = random.Random(config.seed)
    Faker.seed(config.seed)
    fake = Faker(FAKER_LOCALES)
    pools = source_pools(entries)

    true_matches, used_rows, true_match_report = make_true_matches(entries, pools, config, rng)
    hard_negatives, hard_negative_report = make_hard_negatives(entries, pools, config, list_keys, used_rows, rng, fake)
    homonyms: list[dict] = []
    clean, clean_report = make_clean_customers(config, list_keys, rng, fake, homonyms)
    if homonyms_out is not None:
        for number, record in enumerate(homonyms, start=1):
            homonyms_out.append({"customer_id": f"SYN-KYC-H-{number:05d}", **record})

    customers = pd.DataFrame(clean + true_matches + hard_negatives)
    customers.insert(0, "customer_id", [f"SYN-KYC-{i:05d}" for i in range(1, len(customers) + 1)])
    customers["split"] = stratified_split(customers["label"].tolist(), config.seed)
    report = {
        "synthetic": SYNTHETIC_LABEL,
        "seed": config.seed,
        "faker_locales": dict(FAKER_LOCALES),
        "split_fractions": dict(zip(SPLITS, SPLIT_FRACTIONS, strict=True)),
        "source_pool_sizes": {
            f"{source}/{entity_type}": int(len(rows)) for (source, entity_type), rows in pools.items()
        },
        "clean": clean_report,
        "true_match": true_match_report,
        "hard_negative": hard_negative_report,
        "counts_by_label_and_split": {
            label: {
                split: int(((customers["label"] == label) & (customers["split"] == split)).sum()) for split in SPLITS
            }
            for label in LABELS
        },
    }
    return customers, report
