def clean_person_name(fake: Faker) -> str:
    """A Faker person name (may include a title or suffix, as real applications sometimes do)."""
    return fake.name()


def clean_business_name(fake: Faker, rng: random.Random) -> tuple[str, str]:
    """A Faker company name or a composed small-business name; returns (name, generator label).

    Faker's city() is not used: for some locales its output depends on Python's hash seed, which would make
    the customer file differ from run to run despite the fixed seed.
    """
    if rng.random() < 0.5:
        return fake.company(), "faker_company"
    first = rng.choice([fake.last_name(), rng.choice(DESCRIPTIVE_WORDS)])
    return f"{first} {rng.choice(BUSINESS_WORDS)} {rng.choice(LEGAL_SUFFIXES)}", "composed_business"


def clean_country(rng: random.Random) -> str | None:
    """85% US, 10% another trading-partner country, 5% not given."""
    draw = rng.random()
    if draw < 0.85:
        return "US"
    if draw < 0.95:
        return rng.choice(CLEAN_OTHER_COUNTRIES)
    return None


def collision_key(name: str, entity_type: str | None) -> str:
    """Normalized tokens in sorted order: two names with the same key are the same name for screening."""
    return normalize_name(name, entity_type).sorted_key


def list_collision_keys(entries: pd.DataFrame) -> set[str]:
    """Collision keys of every list name and alias (each normalized with its own entity type)."""
    keys: set[str] = set()
    for name, aliases, entity_type in zip(entries["name"], entries["aliases"], entries["entity_type"], strict=True):
        for text in (name, *aliases):
            key = collision_key(text, entity_type)
            if key:
                keys.add(key)
    return keys


# ---------------------------------------------------------------------------------------------------------------
# Choosing list entries to derive true matches and hard negatives from
# ---------------------------------------------------------------------------------------------------------------


def latin_tokens(name: str, entity_type: str) -> list[str] | None:
    """Normalized tokens of a name in natural order, or None if any token is not plain Latin letters/digits."""
    tokens = list(normalize_name(natural_order(name, entity_type), entity_type).tokens)
    if not tokens or not all(is_latin_token(token) for token in tokens):
        return None
    return tokens


def usable_source(tokens: list[str] | None, entity_type: str) -> bool:
    """Names that make sensible test cases: persons with 2-4 tokens, organizations with 1-5, 6+ letters."""
    if tokens is None or sum(len(token) for token in tokens) < 6:
        return False
    if entity_type == "person":
        return 2 <= len(tokens) <= 4 and all(len(token) >= 2 for token in tokens)
    return 1 <= len(tokens) <= 5


def source_pools(entries: pd.DataFrame) -> dict[tuple[str, str], np.ndarray]:
    """Row numbers of possible source entries by (source, entity type).

    OFAC SDN entries are all sanctioned. OpenSanctions entries count only when they carry a sanctions program id,
    so true matches come from sanctions lists rather than, for example, PEP or debarment lists.
    """
    pools: dict[tuple[str, str], np.ndarray] = {}
    for source in ("OFAC", "OpenSanctions"):
        for entity_type in ("person", "organization"):
            mask = (entries["source"] == source) & (entries["entity_type"] == entity_type)
            if source == "OpenSanctions":
                mask &= entries["programs"].map(len) > 0
            pools[(source, entity_type)] = np.flatnonzero(mask.to_numpy())
    return pools


def pick_source_name(entries: pd.DataFrame, row: int, rng: random.Random, alias_probability: float) -> str:
    """The primary name, or (sometimes) one of the aliases."""
    aliases = list(entries["aliases"].iat[row])
    if aliases and rng.random() < alias_probability:
        return rng.choice(aliases)
    return entries["name"].iat[row]


